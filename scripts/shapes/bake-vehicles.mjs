// vehicles:bake — write client/shared/vehicle-models.js from content/vehicle_models/*.json.
//
//   npm run vehicles:bake
//
// The sibling of models:bake, for the other renderer. A building model is authored geometry that
// has to be compiled into affine triples; a vehicle row is plain numbers, so this bake resolves
// nothing and only moves them: it reads the directory, checks each file against the schema, refuses
// two files claiming one row, and writes the module aircraft3d.js imports.
//
// WHY A BAKE AND NOT A RUNTIME READ, same answer as the buildings: aircraft3d.js runs in a browser,
// there is no build step, and a mesh is built on the hot path. A module of literals costs nothing
// at runtime and cannot fail halfway.
//
// ⚠ Re-run after editing any file under content/vehicle_models/. `npm run shapes:smoke` fails if
// you forget — it re-bakes in memory and diffs against the committed file.
import { writeFileSync, readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateVehicleRow, VEHICLE_IDS, vehicleFileName } from '../../client/shared/vehicle-model-schema.js';

const ROOT = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const SRC = join(ROOT, 'content', 'vehicle_models');
const OUT = join(ROOT, 'client', 'shared', 'vehicle-models.js');

export function readVehicleFiles(dir = SRC) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => ({ file: f, doc: JSON.parse(readFileSync(join(dir, f), 'utf8')) }));
}

export function bakeVehicles(files = readVehicleFiles()) {
  const rows = { fw: {}, truck: {} }, errors = [], warnings = [];
  for (const { file, doc } of files) {
    const v = validateVehicleRow(doc, file);
    errors.push(...v.errors); warnings.push(...v.warnings);
    if (v.errors.length) continue;
    // The name is derived from the row, so a file cannot be authored under one id and read as
    // another — the trap that a directory keyed on filename has and a table does not.
    const want = vehicleFileName(doc.kind, doc.id);
    if (file !== want) { errors.push(file + ': a ' + doc.kind + ' row for ' + doc.id + ' must be called ' + want); continue; }
    if (rows[doc.kind][doc.id]) { errors.push(file + ': ' + doc.kind + '/' + doc.id + ' is authored twice'); continue; }
    rows[doc.kind][doc.id] = doc.params;
  }
  // A missing row is a class the renderer would fall back on for, silently, so it is an error and
  // not a warning: the file is how that airframe gets its shape.
  for (const kind of Object.keys(VEHICLE_IDS)) {
    for (const id of VEHICLE_IDS[kind]) {
      if (!rows[kind][id]) errors.push('no file for ' + kind + '/' + id + ' (' + vehicleFileName(kind, id) + ')');
    }
  }
  return { rows, errors, warnings };
}

// Keys in authored order per row is not available (JSON objects are read sorted by the writer), so
// this prints them sorted — the same order canonicalJson puts them in the file, which keeps the
// bake diff and the content diff readable side by side.
function lit(v, indent) {
  if (v === null || typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map((x) => lit(x, indent)).join(', ') + ']';
  const inner = Object.keys(v).sort().map((k) => JSON.stringify(k) + ': ' + lit(v[k], indent));
  return '{ ' + inner.join(', ') + ' }';
}

export function renderModule({ rows }) {
  const table = (kind) => Object.keys(rows[kind]).sort()
    .map((id) => '  ' + JSON.stringify(id) + ': ' + lit(rows[kind][id]) + ',').join('\n');
  return [
    '// GENERATED by scripts/shapes/bake-vehicles.mjs — never edit by hand.',
    '//',
    '// One row per generated vehicle, read straight out of content/vehicle_models/*.json. These are',
    '// the numbers aircraft3d.js builds a mesh from; nothing here is geometry, and the hand-authored',
    '// meshes (the Mayfly, the Cub, both helicopters, the wreck) deliberately have no row.',
    '//',
    '// Re-run `npm run vehicles:bake` after editing any of those files. `npm run shapes:smoke` fails',
    '// on a stale bake rather than letting the module and the content disagree.',
    'export const FW_ROWS = {',
    table('fw'),
    '};',
    'export const TRUCK_ROWS = {',
    table('truck'),
    '};',
    '',
  ].join('\n');
}

export function bakeToString(files) {
  const res = bakeVehicles(files);
  return { ...res, text: res.errors.length ? null : renderModule(res) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { errors, warnings, text } = bakeToString();
  for (const w of warnings) console.warn('warn: ' + w);
  if (errors.length) { for (const e of errors) console.error('error: ' + e); process.exit(1); }
  writeFileSync(OUT, text);
  console.log('vehicles:bake → client/shared/vehicle-models.js');
}
