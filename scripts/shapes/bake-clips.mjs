// clips:bake: write client/game/js/panels/diamond/clips.js from content/animation_clips/*.json.
//
//   npm run clips:bake
//
// The clip library is content with no table, like the building, vehicle and fauna models: one file a
// clip, versioned in git, baked into a module the client imports (the Grandstand runs in a browser
// with no build step, and a clip is read on the hot path). The bake checks each file
// (diamond/clip-schema.js validateClip), refuses two files claiming one clip, and fills in every
// key's pose (diamond/anim.js completePose), so playback only interpolates.
//
// Re-run it after editing any file under content/animation_clips/. anim-smoke fails on a stale bake:
// it bakes again in memory and compares. The Modelshop's Pose Lab saves through `planSave`, which
// bakes the library with the posted clip in place before anything's written.
import { writeFileSync, readFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateClip, formatClip, clipFileName } from '../../client/game/js/panels/diamond/clip-schema.js';
import { completePose } from '../../client/game/js/panels/diamond/anim.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
export const CLIP_DIR = join(ROOT, 'content', 'animation_clips');
export const CLIP_MODULE = join(ROOT, 'client', 'game', 'js', 'panels', 'diamond', 'clips.js');

export function readClipFiles(dir = CLIP_DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => ({ file: f, doc: JSON.parse(readFileSync(join(dir, f), 'utf8')) }));
}

// { clips, errors, warnings }: every clip that checks out, by id, with its keys completed.
export function bakeClips(files = readClipFiles()) {
  const clips = {}, errors = [], warnings = [];
  for (const { file, doc } of files) {
    const v = validateClip(doc, file);
    errors.push(...v.errors); warnings.push(...v.warnings);
    if (v.errors.length) continue;
    if (clips[doc.id]) { errors.push(`${file}: ${doc.id} is keyed twice`); continue; }
    clips[doc.id] = {
      id: doc.id, role: doc.role, duration: doc.duration, loop: !!doc.loop,
      events: (doc.events || []).map((e) => ({ ...e })).sort((a, b) => a.t - b.t),
      plants: (doc.plants || []).map((p) => ({ ...p })).sort((a, b) => a.from - b.from),
      keys: doc.keys.map((k) => ({ t: k.t, ...(k.tension ? { tension: k.tension } : {}), pose: completePose(k.pose) })),
    };
  }
  return { clips, errors, warnings };
}

// Keys sorted, so the module reads the same whatever order a file wrote them in.
function lit(v) {
  if (typeof v === 'number') return Object.is(v, -0) ? '0' : JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(lit).join(', ') + ']';
  if (v && typeof v === 'object') return '{ ' + Object.keys(v).sort().map((k) => JSON.stringify(k) + ': ' + lit(v[k])).join(', ') + ' }';
  return JSON.stringify(v);
}

export function renderModule({ clips }) {
  const out = [
    '// GENERATED by scripts/shapes/bake-clips.mjs from content/animation_clips/. Don\'t edit it by hand:',
    '// edit the clip and run `npm run clips:bake`. anim-smoke fails on a stale bake.',
    '//',
    '// The clip library (diamond/anim.js plays it). Every key\'s pose is complete, so playback only',
    '// interpolates; the clips are frozen, because every player shares them.',
    '',
    'const freeze = (v) => { if (v && typeof v === \'object\') { Object.freeze(v); for (const k of Object.keys(v)) freeze(v[k]); } return v; };',
    '',
    'export const CLIPS = freeze({',
  ];
  for (const id of Object.keys(clips).sort()) {
    const c = clips[id];
    out.push(`  ${JSON.stringify(id)}: {`);
    out.push(`    id: ${JSON.stringify(c.id)}, role: ${JSON.stringify(c.role)}, duration: ${lit(c.duration)}, loop: ${c.loop},`);
    out.push(`    events: ${lit(c.events)},`);
    out.push(`    plants: ${lit(c.plants)},`);
    out.push('    keys: [');
    for (const k of c.keys) out.push(`      { t: ${lit(k.t)}, ${k.tension ? `tension: ${lit(k.tension)}, ` : ''}pose: ${lit(k.pose)} },`);
    out.push('    ],');
    out.push('  },');
  }
  out.push('});', '');
  return out.join('\n');
}

export function bakeToString(files) {
  const res = bakeClips(files);
  return { ...res, text: res.errors.length ? null : renderModule(res) };
}

// A save from the Pose Lab, worked out whole before anything's written: the clip checked by the
// schema, then the library baked with it in place of its own file. Returns { file, errors,
// warnings } and, when there are no errors, `text` for the clip's file (formatClip, which reads
// back as the same clip) and `module` for clips.js. Pure, so anim-smoke checks it.
export function planSave(files, doc) {
  const file = doc && typeof doc.id === 'string' ? clipFileName(doc.id) : '<posted>';
  const pre = validateClip(doc, file);
  if (pre.errors.length) return { file, errors: pre.errors, warnings: pre.warnings };
  const text = formatClip(doc);
  const next = [...files.filter((f) => f.file !== file), { file, doc: JSON.parse(text) }].sort((a, b) => (a.file < b.file ? -1 : 1));
  const res = bakeToString(next);
  return { file, errors: res.errors, warnings: res.warnings, ...(res.errors.length ? {} : { text, module: res.text }) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { errors, warnings, text, clips } = bakeToString();
  for (const w of warnings) console.warn('warn: ' + w);
  if (errors.length) { for (const e of errors) console.error('error: ' + e); process.exit(1); }
  writeFileSync(CLIP_MODULE, text);
  console.log(`clips:bake → client/game/js/panels/diamond/clips.js (${Object.keys(clips).length} clips)`);
}
