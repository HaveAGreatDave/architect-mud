// holoads:bake: write client/shared/holo-ad-spots.js from the 'holo_ad' rows in content/media_graphics.
//
//   npm run holoads:bake            write the module
//   node scripts/content/build-holo-ads.mjs --check     fail if the module is stale (the gate)
//
// A hologram advert is a media_graphics row of type 'holo_ad' whose `content` is JSON:
//
//   { "brand": "ACID COLA",            the name, as it's lettered
//     "line": "Reality Hurts.",        the tagline
//     "small": "…",                    the small print (optional)
//     "color": "#b8ff3a",              the light it's projected in
//     "accent": "#e8ffb0",             the lettering
//     "face": "block|serif|script|mono",
//     "motif": "burst|rings|grid|bars|none",
//     "weight": 1 }                    1 to 4: how often it comes round
//
// The renderer runs in a browser with no build step and can't read content/, so the rows are baked
// into a module, as building models are. Edit the row, then re-run this. The gate fails a stale bake.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'content', 'media_graphics');
const OUT = join(ROOT, 'client', 'shared', 'holo-ad-spots.js');
const FACES = ['block', 'serif', 'script', 'mono'], MOTIFS = ['burst', 'rings', 'grid', 'bars', 'none'];
const HEX = /^#[0-9a-f]{6}$/i;

export function bake() {
  const spots = [], errors = [];
  for (const f of readdirSync(SRC).filter((n) => n.endsWith('.json')).sort()) {
    const row = JSON.parse(readFileSync(join(SRC, f), 'utf8'));
    if (row.type !== 'holo_ad') continue;
    let d;
    try { d = JSON.parse(row.content); } catch (e) { errors.push(`${f}: content isn't JSON (${e.message})`); continue; }
    const bad = (m) => errors.push(`${f}: ${m}`);
    if (!d.brand || typeof d.brand !== 'string') bad('needs a brand');
    if (d.brand && d.brand.length > 28) bad('brand is over 28 characters');
    if (!d.line || typeof d.line !== 'string') bad('needs a line');
    if (d.line && d.line.length > 60) bad('line is over 60 characters');
    if (d.small && d.small.length > 90) bad('small is over 90 characters');
    if (!HEX.test(d.color || '')) bad('color must be #rrggbb');
    if (d.accent && !HEX.test(d.accent)) bad('accent must be #rrggbb');
    if (d.face && !FACES.includes(d.face)) bad(`face must be one of ${FACES.join(', ')}`);
    if (d.motif && !MOTIFS.includes(d.motif)) bad(`motif must be one of ${MOTIFS.join(', ')}`);
    spots.push({
      id: row.id, brand: d.brand, line: d.line, ...(d.small ? { small: d.small } : {}),
      color: d.color, accent: d.accent || '#ffffff', face: d.face || 'block', motif: d.motif || 'none',
      weight: Math.max(1, Math.min(4, d.weight | 0 || 1)),
    });
  }
  const body = '// Generated by `npm run holoads:bake` from the holo_ad rows in content/media_graphics. Don\'t edit.\n'
    + 'export const HOLO_SPOTS = ' + JSON.stringify(spots, null, 1) + ';\n';
  return { spots, errors, body };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === join(process.argv[1])) {
  const { spots, errors, body } = bake();
  if (errors.length) { for (const e of errors) console.error('holoads: ' + e); process.exit(1); }
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing is stale */ }
    if (have !== body) { console.error('holoads: client/shared/holo-ad-spots.js is stale. Run `npm run holoads:bake`.'); process.exit(1); }
    // And the schedule the renderer reads: every screen shows something, the same thing for the same
    // clock, a shop's spot says how to walk there, and both kinds of spot come round.
    const { holoNow, walkWords, SPOT_MS } = await import('../../client/shared/holo-ads.js');
    const fail = (m) => { console.error('holoads: ' + m); process.exit(1); };
    if (walkWords(2, -3) !== '3 NORTH 2 EAST' || walkWords(-1, 0) !== '1 WEST' || walkWords(0, 4) !== '4 SOUTH') fail('walkWords gives the wrong walk');
    const shops = [{ name: 'Test Shop', trade: 'GROCERY', dx: 2, dy: -3 }];
    let shop = 0, authored = 0;
    for (let i = 0; i < 400; i++) {
      const a = holoNow(i * 37 + 1, i * SPOT_MS, shops), b = holoNow(i * 37 + 1, i * SPOT_MS, shops);
      if (!a || !a.spot || !(a.card >= 0 && a.card < 3)) fail('a screen with shops near it showed nothing');
      if (a.spot.id !== b.spot.id || a.card !== b.card) fail('the schedule gave two answers for one clock');
      if (a.spot.shop) { shop++; if (a.spot.small !== '3 NORTH 2 EAST') fail('a shop spot lost its walk'); } else authored++;
      if (!holoNow(i, i * 1000, [])) fail('a screen with no shops near it showed nothing');
    }
    if (!shop || !authored) fail(`only one kind of spot came round (${shop} shop, ${authored} authored)`);
  } else {
    writeFileSync(OUT, body);
    console.log(`holoads: ${spots.length} spot(s) → client/shared/holo-ad-spots.js`);
  }
}
