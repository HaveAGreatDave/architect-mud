// Build the backlot: the stock sets a film is staged on when its scene has no set of its own.
//
//   node scripts/content/build-film-sets.mjs            write them
//   node scripts/content/build-film-sets.mjs --table    and print which set every SLUG in every film gets
//
// WHAT IT WRITES
//   content/media_graphics/set_film_*.json   one set per kind of place: an office, a corridor, a
//                                            stairwell, a bar, a shop, a street at night, an alley, a
//                                            flat, a rich man's lounge, a kitchen, a works floor, a
//                                            workshop, a brick tunnel, a civic hall, a yard, a pool
//                                            deck (full and drained), open ground, and grand steps
//
// HOW A FILM USES THEM. A film's SLUG line (`SLUG THE OFFICE | BEFORE DAWN`) is a lower third. As it
// airs, the broadcast plugin asks sceneSetFor (plugins/broadcast/sequences.js) which backlot set the
// words name, and the 3-D stage changes to it. Each set's `scenes` is phrase → weight: a word for the
// kind of room ("office", "kitchen") weighs 3, an area or an address ("street", "the basin") 1 or 2,
// and a place in one of our films ("the embassy", "the deep floor") whatever it needs to win. A phrase
// counts double before the pipe, where the place is. A SLUG that names nothing keeps the set it's on,
// so "THE HUNT | that same night" stays in the catacombs. `backlot: true` is what makes a set one of
// these; `uses: ['film']` on the street makes it a film's set before its first SLUG.
//
// The pieces are in client/game/js/panels/gl/set-film.js and the other set-*.js files. Marks are in
// the order a film's speakers take them, first speaker first.

