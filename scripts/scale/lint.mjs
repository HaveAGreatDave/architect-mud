// scale:lint: no new copies of the world's scale numbers outside client/shared/world-scale.js.
//
//   npm run scale:lint              check against the baseline (runs in the push gate)
//   npm run scale:lint -- --list    print every counted hit, change nothing
//   npm run scale:lint -- --update  rewrite the baseline after you've moved a copy onto the ruler
//
// docs/proposals/world-scale.md puts the tile size, the unit conversions and the paces in one file.
// This fails when a literal copy of one of them turns up anywhere else in client/, server/,
// plugins/, scripts/ or tools/. The hits that were there when the gate went in are ratcheted per
// file in baseline.json: a file's count may go down, never up, and a new file starts at zero.
//
// What it counts, in code only:
//   17.857, 17.9        a tile in metres (import TILE_M, or m2t/t2m)
//   3.5 / 0.196         the same ruler, worked out again
//   3.28084, 0.3048     feet and metres (import FT_M)
//   0.8689              mph to knots (import KT_MS and MPH_MS)
//   1.688               knots to feet a second (KT_MS / FT_M)
//
// What it leaves out:
//   - comments. A note saying a tile is 17.9 m explains the ruler; it doesn't copy it. A hit after
//     a line's `//`, inside a same-line `/* */`, or on a line that starts with `*` is a comment.
//   - generated files (GENERATED by in the first three lines). Their numbers are baked data, a
//     pose or a mesh vertex that happens to read 0.3048, and the baker would re-add them anyway.
//   - world-scale.js itself, and this file.
//
// No database, no port, and it writes nothing unless --update is passed, so it's safe beside any
// other gate. It reads each file once and only splits the ones the combined pattern matches.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const BASELINE = join(ROOT, 'scripts', 'scale', 'baseline.json');
const UPDATE = process.argv.includes('--update');
const LIST = process.argv.includes('--list');

const ROOTS = ['client', 'server', 'plugins', 'scripts', 'tools'];
const EXT = /\.(m?js|cjs|html)$/;
const SKIP_DIRS = new Set(['node_modules', 'temp']);
const SKIP_FILES = new Set(['client/shared/world-scale.js', 'scripts/scale/lint.mjs']);

// One pattern per number. The lookbehind keeps 17.9 from matching 117.9 or 0.17.9, and the
// lookahead keeps 17.9 from matching 17.95 and 0.3048 from matching 0.30485.
const PATTERNS = [
  { id: '17.857', re: /(?<![\w.])17\.857\d*/g },
  { id: '17.9', re: /(?<![\w.])17\.9(?![\d])/g },
  { id: '3.5/0.196', re: /(?<![\w.])3\.5\s*\/\s*0\.196(?![\d])/g },
  { id: '3.28084', re: /(?<![\w.])3\.28084\d*/g },
  { id: '0.3048', re: /(?<![\w.])0\.3048(?![\d])/g },
  { id: '0.8689', re: /(?<![\w.])0\.8689\d*/g },
  { id: '1.688', re: /(?<![\w.])1\.688(?![\d])/g },
];
const ANY = new RegExp(PATTERNS.map((p) => p.re.source).join('|'));

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || SKIP_DIRS.has(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (EXT.test(e.name)) out.push(p);
  }
  return out;
}

const rel = (p) => relative(ROOT, p).split(sep).join('/');

// Is position `at` on this line inside a comment? A `//` counts when nothing that could end a
// URL scheme (`:`) or open a string sits right before it; good enough for the handful of lines a
// number lands on, and a false call only ever means one hit more or less in a ratchet.
function inComment(line, at) {
  const t = line.trimStart();
  if (t.startsWith('*') || t.startsWith('/*') || t.startsWith('<!--')) return true;
  const pre = line.slice(0, at);
  if (/(^|[^:'"`\\/])\/\//.test(pre)) return true;
  const open = pre.lastIndexOf('/*');
  return open >= 0 && pre.indexOf('*/', open) < 0;
}

const counts = {};
const hits = [];
for (const root of ROOTS) {
  for (const p of walk(join(ROOT, root))) {
    const key = rel(p);
    if (SKIP_FILES.has(key)) continue;
    const src = readFileSync(p, 'utf8');
    if (!ANY.test(src)) continue;
    const lines = src.split(/\r?\n/);
    if (/GENERATED by/.test(lines.slice(0, 3).join('\n'))) continue;
    let n = 0;
    lines.forEach((line, i) => {
      if (!ANY.test(line)) return;
      for (const { id, re } of PATTERNS) {
        re.lastIndex = 0;
        let m;
        while ((m = re.exec(line))) {
          if (inComment(line, m.index)) continue;
          n++;
          hits.push({ key, line: i + 1, id, text: line.trim().slice(0, 140) });
        }
      }
    });
    if (n) counts[key] = n;
  }
}

if (LIST) {
  for (const h of hits) console.log(`${h.key}:${h.line}  [${h.id}]  ${h.text}`);
  console.log(`\n${hits.length} hits in ${Object.keys(counts).length} files.`);
  process.exit(0);
}

if (UPDATE) {
  const sorted = Object.fromEntries(Object.keys(counts).sort().map((k) => [k, counts[k]]));
  writeFileSync(BASELINE, JSON.stringify(sorted, null, 2) + '\n');
  console.log(`scale:lint baseline written: ${hits.length} hits in ${Object.keys(sorted).length} files.`);
  process.exit(0);
}

const base = existsSync(BASELINE) ? JSON.parse(readFileSync(BASELINE, 'utf8')) : {};
const worse = [];
let better = 0;
for (const [key, n] of Object.entries(counts)) {
  const was = base[key] || 0;
  if (n > was) worse.push({ key, n, was });
}
for (const [key, was] of Object.entries(base)) if ((counts[key] || 0) < was) better++;

if (worse.length) {
  console.error('scale:lint: a scale number was copied instead of imported from client/shared/world-scale.js.\n');
  for (const w of worse) {
    console.error(`  ${w.key}: ${w.n} (baseline ${w.was})`);
    for (const h of hits.filter((h) => h.key === w.key)) console.error(`    ${h.line}  [${h.id}]  ${h.text}`);
  }
  console.error('\nImport TILE_M, m2t/t2m, FT_M, NM_M, MI_M, KT_MS, MPH_MS or KMH_MS from client/shared/world-scale.js.');
  console.error('If the number is a coincidence (a hash seed, a pose), run npm run scale:lint -- --update and say why in the commit.');
  process.exit(1);
}
if (better) console.log(`scale:lint: ${better} file(s) dropped below the baseline; run npm run scale:lint -- --update to lock it in.`);
