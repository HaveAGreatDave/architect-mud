// skillCheck succeeds when gap + swing >= 0 with an integer swing, so a
// fractional gap (a deck's hack_penalty can be fractional) acts as floor(gap).
export function gapOf(skill, difficulty) {
  return Math.max(GAP_MIN, Math.min(GAP_MAX, Math.floor(skill - difficulty)));
}

export function boardFor(skill, difficulty) {
  const pins = pinsFor(difficulty);
  const gap = gapOf(skill, difficulty);
  return { pins, track: TRACK, width: WIDTH, capacity: CAPACITY[pins][gap - GAP_MIN], gap };
}

// A fresh lock. The rated capacity rolls to one of the two whole numbers beside
// it, and the board says which before the first move, so nothing is hidden.
// Internally a window is its first cell, 0-based.
export function newLock({ pins, track = TRACK, width = WIDTH, capacity: rated }, rng = Math.random) {
  const whole = Math.floor(rated);
  const capacity = whole + (rng() < rated - whole ? 1 : 0);
  const starts = [];
  for (let i = 0; i < pins; i++) starts.push(Math.floor(rng() * (track - width + 1)));
  return {
    pins, track, width, capacity, starts,
    pin: 0, feedback: 0, over: capacity <= 0, won: false,
    known: { lo: 0, hi: track - width },   // where the current pin's window can still be
  };
}

// One move. `cell` is 0-based.
//   set    in the window: the pin locks, free. Outside: FEEDBACK +3, and the
//          lock shows which side of the cell the window is on.
//   probe  FEEDBACK +1 whatever happens. In the window: the pin locks (a `set`
//          after it would be a keystroke with no decision in it). Outside:
//          which side, as above.
// Returns 'set' | 'here' | 'left' | 'right'. 'left' means the window is wholly
// below the cell, 'right' wholly above.
export function act(lock, move, cell) {
  if (lock.over) throw new Error('lock is finished');
  const s = lock.starts[lock.pin];
  const inWindow = cell >= s && cell <= s + lock.width - 1;
  const side = cell < s ? 'right' : 'left';
  let answer;
  if (move === 'set') {
    if (inWindow) answer = 'set';
    else { answer = side; lock.feedback += COST.miss; }
  } else {
    lock.feedback += COST.probe;
    answer = inWindow ? 'here' : side;
  }
  if (answer === 'set' || answer === 'here') {
    lock.pin++;
    lock.known = { lo: 0, hi: lock.track - lock.width };
  } else if (answer === 'right') {
    lock.known = { lo: Math.max(lock.known.lo, cell + 1), hi: lock.known.hi };
  } else {
    lock.known = { lo: lock.known.lo, hi: Math.min(lock.known.hi, cell - lock.width) };
  }
  if (lock.feedback >= lock.capacity) { lock.over = true; lock.won = false; }
  else if (lock.pin >= lock.pins) { lock.over = true; lock.won = true; }
  return answer;
}
