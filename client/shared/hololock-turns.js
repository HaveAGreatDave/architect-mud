  4: [0.00, 1.72, 3.16, 4.14, 5.00, 5.52, 6.13, 6.60, 7.11, 7.50, 7.98, 8.32, 8.71, 9.10, 9.44, 9.79, 10.13, 10.47, 10.76, 11.04, 11.40, 11.69, 11.90, 12.18, 12.54, 12.77, 12.90, 12.97, 12.99, 13.00],
