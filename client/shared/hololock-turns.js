  6: [0.00, 5.78, 7.23, 8.26, 9.12, 9.81, 10.36, 11.01, 11.44, 12.01, 12.42, 12.92, 13.34, 13.78, 14.20, 14.60, 14.99, 15.39, 15.75, 16.10, 16.50, 16.82, 17.15, 17.57, 17.84, 18.09, 18.61, 18.87, 18.97, 19.00],
