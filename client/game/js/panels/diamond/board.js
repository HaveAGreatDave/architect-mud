/**
 * DEADBALL — what the scoreboard says.
 *
 * The board behind right-centre is a face of lamps, 240 across and 84 down. This works out
 * which lamps are lit from the game as the payloads tell it: the line score by inning with
 * R, H and E, the count and the outs, and who's batting and pitching. gl/ballpark.js uploads
 * the result as a one-channel texture and draws each lamp in the shader, so a new line costs
 * 20 KB of upload and no canvas.
 *
 * The lettering is a 5×7 matrix face, the one the period's boards used. Pure: the gate runs it.
 */

export const BOARD_W = 240, BOARD_H = 84;

