// Letters a lamp's width apart, six lamps a character.
function text(m, x, y, s) {
  for (const ch of String(s).toUpperCase()) {
    const g = GLYPHS[ch];
    if (g) for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) {
      if (!(g[r] & (0x10 >> c))) continue;
      const px = x + c, py = y + r;
      if (px >= 0 && px < BOARD_W && py >= 0 && py < BOARD_H) m[py * BOARD_W + px] = 255;
    }
    x += 6;
  }
}
const right = (m, x, y, s) => text(m, x - String(s).length * 6, y, s);

// The lamps for this state of the game. `s` is what the view knows:
//   away, home      the clubs' tags
//   line            the payload's line score ({ away: [...], home: [...], hAway, hHome, eAway?, eHome? })
//   aScore, hScore  the runs
//   inning, half    where the game is
//   balls, strikes, outs
//   batter, pitcher
export function boardLamps(s = {}) {
  const m = new Uint8Array(BOARD_W * BOARD_H);
  const line = s.line || {};
  const A = Array.isArray(line.away) ? line.away : [], H = Array.isArray(line.home) ? line.home : [];
  const played = Math.max(A.length, H.length, s.inning | 0);
  // nine columns of innings, the latest nine in extras
  const first = Math.max(1, played - 8);
  const E = line.eAway != null;
  const col = (k) => 36 + k * 18;
  for (let k = 0; k < 9; k++) right(m, col(k) + 12, 2, first + k);
  right(m, 210, 2, 'R'); right(m, 226, 2, 'H'); if (E) right(m, 240, 2, 'E');
  // a club's row: the half's arrow beside the side that's batting, its tag, its runs by
  // inning and the totals
  const row = (y, tag, arr, runs, hits, errs, up) => {
    if (up) text(m, 0, y, up);
    text(m, 8, y, String(tag || '').slice(0, 4));
    for (let k = 0; k < 9; k++) { const v = arr[first - 1 + k]; if (v != null) right(m, col(k) + 12, y, v); }
    right(m, 210, y, runs | 0); right(m, 226, y, hits | 0); if (E) right(m, 240, y, errs | 0);
  };
  const topNow = s.half === 'top';
  row(14, s.away || 'AWY', A, s.aScore, line.hAway, line.eAway, topNow ? '▲' : '');
  row(25, s.home || 'HOM', H, s.hScore, line.hHome, line.eHome, !topNow && s.half ? '▼' : '');
  // the count and the outs
  text(m, 0, 44, `BALL ${s.balls | 0}`); text(m, 72, 44, `STRIKE ${s.strikes | 0}`); text(m, 168, 44, `OUT ${s.outs | 0}`);
  if (s.batter) text(m, 0, 60, `AB ${String(s.batter).slice(0, 36)}`);
  if (s.pitcher) text(m, 0, 72, `P  ${String(s.pitcher).slice(0, 36)}`);
  return m;
}
